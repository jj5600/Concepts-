// numOnes how many binary 1 is present in this uint32 value
uint32_t numOnes(uint32_t a)
{
	uint32_t count;
	asm(

			"mov r2, #1 \n\t" // compare value
			"mov r3, #0 \n\t" // counter
			"loop1: \n\t" //loop
			"CMP r0, #0 \n\t"// see if the input value is 0
			"beq stop \n\t" // if it is 0 then go to stop scenario and begin stop seq
			"AND r1, r0, r2 \n \t" // r1 = r0 & r2(0x1)
			"ADDS r3,r3, r1 \n \t" // add the result of and operation to temp output r3
			"LSR r0,r0, #1\n \t" // right shift the value by 1
			"b loop1 \n\t"
			"stop: \n\t"
			"MOV r0, r3 \n\t" // move result to output
			"mov %[count], r3\n"
			: [count] "=r" (count), [a] "+r" (a)
			:
			: "r1", "r2", "r2", "cc"
			);

	return count;
}
// my disable interrupt funciton
// see Lesson 5 slides -> slide 31
void myDisableIntr(uint32_t IRQn)
{
	if(IRQn >= 0)
		{
			NVIC->ICER[(((uint32_t)IRQn)>>5UL)] = (uint32_t)(1UL << (((uint32_t) IRQn) & 0x1FUL));
		}
}
// my enable interrupt function
void myEnableIntr(uint32_t IRQn)
{
	if(IRQn >= 0)
	{
		NVIC->ISER[(((uint32_t)IRQn)>>5UL)] = (uint32_t)(1UL << (((uint32_t) IRQn) & 0x1FUL));
	}
}
